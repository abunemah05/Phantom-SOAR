#!/usr/bin/env python3
"""Environment for the local development scripts (dev.sh, run_backend.bat, run_frontend.bat).

Prints one NAME=VALUE line per variable to export; the calling script applies them. Nothing secret is
ever written to the terminal. Sources, highest priority first:

  1. variables already set in the calling shell (never overridden)
  2. KEY=VALUE lines of the repo-root .env (comments, blank lines, "export ", matching quotes and
     trailing " # comment" are understood; empty values are skipped, so "KEY=" means "use the default")
  3. random development secrets kept in .phantom_dev_secrets (git-ignored, created with mode 0600 on first
     use and reused afterwards, so sessions and secrets stored in the dev database survive restarts)
  4. development defaults (simulation mode on, loopback API host, CORS for the dev UI)

Standard library only, so it runs before the virtualenv exists. Exit code 0 even when .env is missing.
"""
import base64
import os
import re
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SECRETS_FILE = ROOT / ".phantom_dev_secrets"


def parse_env_file(path):
    """KEY -> value for every usable line; invalid lines are reported on stderr and skipped."""
    values = {}
    try:
        text = path.read_text(encoding="utf-8-sig")
    except OSError:
        return values
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].lstrip()
        key, sep, value = line.partition("=")
        key = key.strip()
        if not sep or not NAME_RE.match(key):
            print(f"[dev] {path.name}:{number}: ignored (not KEY=VALUE)", file=sys.stderr)
            continue
        value = value.strip()
        if value[:1] in "\"'" and value.endswith(value[:1]) and len(value) >= 2:
            value = value[1:-1]
        else:
            value = re.split(r"\s#", value, maxsplit=1)[0].rstrip()
        if value:
            values[key] = value
    return values


def fernet_key():
    """A valid Fernet key (urlsafe base64 of 32 random bytes) without needing the cryptography package."""
    return base64.urlsafe_b64encode(os.urandom(32)).decode("ascii")


def load_dev_secrets():
    wanted = {
        "PHANTOM_JWT_SECRET": lambda: secrets.token_urlsafe(48),
        "PHANTOM_ENCRYPTION_KEY": fernet_key,
        "PHANTOM_INGEST_TOKEN": lambda: secrets.token_urlsafe(32),
    }
    existing = parse_env_file(SECRETS_FILE) if SECRETS_FILE.exists() else {}
    changed = False
    for name, make in wanted.items():
        if not existing.get(name):
            existing[name] = make()
            changed = True
    if changed:
        body = "# Development-only secrets generated by scripts/dev_env.py. Never commit; delete to regenerate.\n"
        body += "".join(f"{k}={existing[k]}\n" for k in wanted)
        fd = os.open(str(SECRETS_FILE), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(body)
        print(f"[dev] created {SECRETS_FILE.name} (development secrets, git-ignored)", file=sys.stderr)
    return {k: existing[k] for k in wanted}


def main():
    env_file = parse_env_file(ROOT / ".env")
    if env_file:
        print(f"[dev] loaded {len(env_file)} value(s) from .env", file=sys.stderr)

    def effective(name):
        return os.environ.get(name) or env_file.get(name) or ""

    out = {name: value for name, value in env_file.items() if not os.environ.get(name)}

    backend_port = effective("BACKEND_PORT") or "8000"
    frontend_port = effective("FRONTEND_PORT") or "3000"
    defaults = {
        "PHANTOM_ENV": "development",
        "PHANTOM_SIMULATION_MODE": "true",
        "BACKEND_HOST": "127.0.0.1",
        "PHANTOM_CORS_ORIGINS": f"http://localhost:{frontend_port},http://127.0.0.1:{frontend_port}",
        "NEXT_PUBLIC_API_URL": f"http://localhost:{backend_port}",
    }
    for name, value in defaults.items():
        if not effective(name):
            out[name] = value

    needs_secrets = [n for n in ("PHANTOM_JWT_SECRET", "PHANTOM_ENCRYPTION_KEY", "PHANTOM_INGEST_TOKEN") if not effective(n)]
    if needs_secrets:
        dev_secrets = load_dev_secrets()
        for name in needs_secrets:
            out[name] = dev_secrets[name]

    for name, value in out.items():
        if "\n" in value or "\r" in value:
            print(f"[dev] {name}: value contains a line break; ignored", file=sys.stderr)
            continue
        print(f"{name}={value}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
